import type { MapStyleDocument, MapStyleLayer } from '@/core/rendering/styles/style-spec'
import { Color } from 'three'
import { MAP_STYLE_SOURCES } from '@/core/data-source/source-registry'
import { KOPPEN_COLORS } from '@/core/simulation/climate/koppen-climate-classifier'
import { BIOME_COLORS } from '@/core/simulation/ecology/biome-data'

export const KOPPEN_HEX_COLORS: string[] = KOPPEN_COLORS.map(c => `#${c.map(v => Math.round(v * 255).toString(16).padStart(2, '0')).join('')}`)
export const BIOME_HEX_COLORS: string[] = BIOME_COLORS.map(c => `#${c.map(v => Math.round(v * 255).toString(16).padStart(2, '0')).join('')}`)
export const PLATE_HEX_COLORS: string[] = Array.from({ length: 128 }, (_, id) => {
  const hue = ((id * 137.508) % 360) / 360
  const color = new Color().setHSL(hue, 0.65, 0.55)
  return `#${color.getHexString()}`
})

function geographicThematicFillLayers(fillOpacity = 0.65): MapStyleLayer[] {
  const thematicAreas = [
    { id: 'plates', source: 'plate-areas', colors: PLATE_HEX_COLORS },
    { id: 'continents', source: 'continent-areas', colors: PLATE_HEX_COLORS },
    { id: 'koppen', source: 'koppen-areas', colors: KOPPEN_HEX_COLORS },
    { id: 'biome', source: 'biome-areas', colors: BIOME_HEX_COLORS },
  ] as const

  return thematicAreas.map(({ id, source, colors }): MapStyleLayer => ({
    id: `${id}-fill`,
    source,
    renderer: 'fill',
    thematic: id,
    views: ['map', 'globe'],
    minZoom: 0,
    maxZoom: 24,
    layout: { 'visibility': 'visible' },
    paint: { 'fill-color': ['palette', ['get', 'groupId'], ['literal', colors]], 'fill-opacity': fillOpacity },
  }))
}

