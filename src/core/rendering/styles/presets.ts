function createPreset(
  id: string,
  name: string,
  description: string,
  tokens: MapStyleDocument['tokens'],
): MapStyleDocument {
  return {
    version: 1,
    id,
    name,
    description,
    tokens,
    sources: Object.fromEntries(Object.entries(MAP_STYLE_SOURCES).map(([key, source]) => [key, { ...source, properties: [...source.properties] }])),
    layers: commonLayers.map(layer => ({
      ...layer,
      views: layer.views ? [...layer.views] : undefined,
      baseMaps: layer.baseMaps ? [...layer.baseMaps] : undefined,
      layout: { ...layer.layout },
      paint: { ...layer.paint },
    })),
  }
}

