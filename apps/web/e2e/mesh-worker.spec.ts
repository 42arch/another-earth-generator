import { expect, test } from '@playwright/test'

test('real Worker builds, reuses cache, and recovers after hard cancellation', async ({ page }) => {
  await page.goto('/mesh-debug')
  const generate = page.getByRole('button', { name: 'Generate' })
  const pipeline = page.locator('dt').filter({ hasText: /^Pipeline$/ }).locator('xpath=following-sibling::dd[1]')
  const regions = page.locator('dt').filter({ hasText: /^Regions \/ V$/ }).locator('xpath=following-sibling::dd[1]')
  await expect(page.getByLabel('细分等级').locator('option')).toHaveCount(5)
  await expect(page.getByLabel('细分等级')).toHaveValue('4')
  await expect(page.getByLabel('细分等级').locator('option', { hasText: /^L[0-3] ·/ })).toHaveCount(0)
  await expect(page.getByLabel('细分等级').locator('option', { hasText: /^L8 ·/ })).toHaveCount(1)
  const fiveNeighborToggle = page.getByLabel('显示五邻域中心（橙点）')
  await expect(fiveNeighborToggle).not.toBeChecked()
  await fiveNeighborToggle.check()
  await expect(fiveNeighborToggle).toBeChecked()
  await fiveNeighborToggle.uncheck()
  await page.locator('input[type="range"]').first().fill('0.5')
  await page.getByLabel('细分等级').selectOption('4')
  await generate.click()
  await expect(pipeline).toHaveText('Rebuilt')
  await expect(regions).toHaveText('2,562')
  await fiveNeighborToggle.check()
  await expect(pipeline).toHaveText('Rebuilt')
  await fiveNeighborToggle.uncheck()
  await generate.click()
  await expect(pipeline).toHaveText('Cache Hit')

  await page.getByLabel('细分等级').selectOption('7')
  await generate.click()
  await page.getByRole('button', { name: 'Cancel' }).click()
  await expect(regions).toHaveText('2,562')
  await page.getByLabel('细分等级').selectOption('4')
  await generate.click()
  await expect(pipeline).toHaveText('Rebuilt')
  await expect(regions).toHaveText('2,562')
})

test('a Worker stage failure keeps the previous visible mesh', async ({ page }) => {
  await page.addInitScript(() => {
    const NativeWorker = window.Worker
    window.Worker = class extends NativeWorker {
      override postMessage(message: unknown, transfer?: Transferable[]): void {
        const request = message as { type?: string, input?: { seed?: string, config?: { mesh?: { subdivisionLevel?: number } } } }
        if (request.type === 'GENERATE' && request.input?.seed === 'fail-once') {
          const invalid = { ...request, input: { ...request.input, config: { ...request.input.config, mesh: { ...request.input.config?.mesh, subdivisionLevel: 9 } } } }
          super.postMessage(invalid, transfer ?? [])
          return
        }
        super.postMessage(message, transfer ?? [])
      }
    }
  })
  await page.goto('/mesh-debug')
  const generate = page.getByRole('button', { name: 'Generate' })
  const regions = page.locator('dt').filter({ hasText: /^Regions \/ V$/ }).locator('xpath=following-sibling::dd[1]')
  await generate.click()
  await expect(regions).toHaveText('2,562')
  await page.getByLabel('Seed').fill('fail-once')
  await generate.click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(regions).toHaveText('2,562')
  await page.getByLabel('Seed').fill('42')
  await generate.click()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await expect(regions).toHaveText('2,562')
})

test('M1.1A geology renders on mesh-debug and reuses only unaffected stages', async ({ page }) => {
  test.setTimeout(60_000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/mesh-debug')
  await page.getByLabel('生成内容').selectOption('geology')
  await page.getByLabel('细分等级').selectOption('4')
  await page.getByRole('button', { name: 'Generate' }).click()
  const results = page.getByRole('region', { name: '地质结果', exact: true })
  await expect(results).toBeVisible({ timeout: 30_000 })
  await expect(results).toContainText('40,962')
  await expect(page.getByRole('alert')).toHaveCount(0)
  const cache = page.getByLabel('阶段缓存')
  await expect(cache).toContainText('plate-topology: Rebuilt')
  await page.getByLabel('地质专题').selectOption('crust')
  await expect(cache).toContainText('continental-crust: Rebuilt')
  const canvas = page.locator('canvas')
  await canvas.click({ position: { x: (await canvas.boundingBox())!.width / 2, y: (await canvas.boundingBox())!.height / 2 } })
  await expect(page.getByLabel('选中区域')).toContainText('g/cm³')
  await page.getByRole('button', { name: 'Generate' }).click()
  await expect(cache).toContainText('continental-crust: Cache Hit')
  await page.getByLabel('候选大陆目标数', { exact: true }).fill('3')
  await page.getByRole('button', { name: 'Generate' }).click()
  await expect(cache).toContainText('continental-crust: Rebuilt')
  await expect(cache).toContainText('plate-topology: Cache Hit')
  await page.getByRole('button', { name: '强制重算' }).click()
  await page.getByRole('button', { name: 'Cancel' }).click()
  await expect(results).toBeVisible()
  await page.getByRole('button', { name: 'Generate' }).click()
  await expect(page.getByRole('status')).toContainText('板块与地壳已就绪', { timeout: 30_000 })
  await expect(page.getByRole('alert')).toHaveCount(0)
  expect(errors).toEqual([])
})

