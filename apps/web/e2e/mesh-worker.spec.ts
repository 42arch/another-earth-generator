async function openInspector(page: Page): Promise<void> {
  const parameters = page.getByRole('button', { name: '参数', exact: true })
  if (await parameters.getAttribute('aria-expanded') === 'true')
    await parameters.click()
  const inspector = page.getByRole('button', { name: '侦测' })
  if (await inspector.getAttribute('aria-expanded') !== 'true')
    await inspector.click()
}

async function closeInspector(page: Page): Promise<void> {
  const inspector = page.getByRole('button', { name: '侦测' })
  if (await inspector.getAttribute('aria-expanded') === 'true')
    await inspector.click()
  const parameters = page.getByRole('button', { name: '参数', exact: true })
  if (await parameters.getAttribute('aria-expanded') !== 'true')
    await parameters.click()
}

async function expectReadyStatus(page: Page, text: string, timeout = 30_000): Promise<void> {
  await expect(page.getByRole('status').filter({ hasText: text })).toBeVisible({ timeout })
}

async function adjustSlider(page: Page, name: string, target: number, step: number): Promise<void> {
  const slider = page.getByRole('slider', { name })
  await slider.focus()
  const current = Number(await slider.getAttribute('aria-valuenow'))
  const key = target >= current ? 'ArrowRight' : 'ArrowLeft'
  const steps = Math.round(Math.abs(target - current) / step)
  for (let index = 0; index < steps; index++)
    await slider.press(key)
}

function themeButton(page: Page, name: string) {
  return page.getByRole('button', { name, exact: true })
}

