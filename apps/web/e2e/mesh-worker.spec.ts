test('L8 terrain retains its full Worker stage chain in the expanded cache', async ({ page }) => {
  test.setTimeout(120_000)
  await page.goto('/mesh-debug')
  await page.getByLabel('生成内容').selectOption('terrain')
  await page.getByLabel('细分等级').selectOption('8')
  const generate = page.getByRole('button', { name: 'Generate' })
  const pipeline = page.locator('dt').filter({ hasText: /^Pipeline$/ }).locator('xpath=following-sibling::dd[1]')
  const cacheBytes = page.locator('dt').filter({ hasText: /^缓存数组$/ }).locator('xpath=following-sibling::dd[1]')
  await generate.click()
  await expect(page.getByRole('status')).toContainText('最终地形已就绪', { timeout: 90_000 })
  await expect(pipeline).toHaveText('Rebuilt')
  await expect(cacheBytes).toContainText('MiB')
  const firstCacheMiB = Number(((await cacheBytes.textContent()) ?? '').replace('MiB', '').trim())
  expect(firstCacheMiB).toBeGreaterThan(350)
  await generate.click()
  await expect(pipeline).toHaveText('Cache Hit', { timeout: 30_000 })
})
